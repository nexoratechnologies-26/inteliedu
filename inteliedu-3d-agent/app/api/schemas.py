"""Pydantic schemas for requests, storyboards, validation, and metadata."""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Dict, List, Literal, Optional

from pydantic import BaseModel, Field, field_validator


class GenerationRequest(BaseModel):
    """Input payload from INTELIEDU Supervisor Agent or Backend API."""

    topic: str = Field(..., min_length=2, max_length=300, description="Student question or topic")
    class_level: int = Field(default=8, alias="class", ge=1, le=12, description="Student class (6-12)")
    subject: str = Field(default="Science", max_length=100)
    board: str = Field(default="State Board", max_length=100)
    chapter: Optional[str] = Field(default=None, max_length=200)
    educational_context: Optional[str] = Field(
        default=None, description="Curriculum snippet or RAG context from Supervisor Agent"
    )
    language: str = Field(default="English", max_length=50)
    duration: int = Field(default=60, ge=5, le=300, description="Requested video duration in seconds")
    include_narration: bool = Field(default=True)
    include_subtitles: bool = Field(default=True)
    narration_audio_path: Optional[str] = Field(
        default=None, description="Optional pre-generated audio file from Audio Agent"
    )
    prefer_runway: bool = Field(
        default=False, description="Allow Runway supplementary generation when appropriate"
    )
    force_regenerate: bool = Field(
        default=False, description="Bypass duplicate video cache"
    )

    model_config = {"populate_by_name": True}

    @field_validator("topic", "subject", "board", "language")
    @classmethod
    def strip_text(cls, value: str) -> str:
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("Field cannot be blank")
        return cleaned


class PlanRequest(BaseModel):
    """Request to understand a topic and plan a storyboard without rendering."""

    topic: str = Field(..., min_length=2, max_length=300)
    class_level: int = Field(default=8, alias="class", ge=1, le=12)
    subject: str = Field(default="Science", max_length=100)
    board: str = Field(default="State Board", max_length=100)
    chapter: Optional[str] = Field(default=None, max_length=200)
    educational_context: Optional[str] = Field(default=None)
    language: str = Field(default="English", max_length=50)
    duration: int = Field(default=60, ge=5, le=300)
    include_narration: bool = Field(default=True)
    include_subtitles: bool = Field(default=True)

    model_config = {"populate_by_name": True}


class TopicUnderstanding(BaseModel):
    """Structured output from Module 1: Topic Understanding."""

    topic: str
    normalized_topic: str
    class_level: int = Field(alias="class")
    board: str
    subject: str
    chapter: str
    learning_objective: str
    key_concepts: List[str] = Field(default_factory=list)
    visualization_type: str
    video_required: bool
    video_requirement_reason: str
    estimated_duration: int
    complexity: Literal["low", "medium", "high"] = "medium"
    template_key: str = "generic_stem"
    recommended_engine: Literal["blender", "existing_asset_blender", "runway", "hybrid", "none"] = "blender"
    requires_runway_clip: bool = False
    existing_asset_filename: Optional[str] = None
    educational_notes: List[str] = Field(default_factory=list)

    model_config = {"populate_by_name": True}


class SceneSpec(BaseModel):
    """Structured storyboard specification for a single educational scene."""

    scene_id: int = Field(..., ge=1)
    title: str
    educational_objective: str
    description: str
    objects: List[str] = Field(default_factory=list)
    camera_position: str = "front-elevated"
    camera_movement: str = "smooth_orbit"
    object_movement: str = "continuous_educational_motion"
    animation_instructions: str
    duration: int = Field(..., ge=2, le=120)
    narration: str = ""
    transition: str = "crossfade"
    render_engine: Literal["blender", "existing_asset_blender", "runway"] = "blender"
    template_name: str = "generic_stem"
    runway_prompt: Optional[str] = None
    labels: List[str] = Field(default_factory=list)


class Storyboard(BaseModel):
    """Complete educational video storyboard generated by Module 2."""

    video_title: str
    topic: str
    class_level: int = Field(alias="class")
    subject: str
    board: str
    chapter: str
    language: str = "English"
    total_duration: int
    scale_disclosure: Optional[str] = None
    scientific_accuracy_notes: List[str] = Field(default_factory=list)
    scenes: List[SceneSpec] = Field(default_factory=list)

    model_config = {"populate_by_name": True}


class TechnicalValidationResult(BaseModel):
    passed: bool
    file_exists: bool = False
    can_open: bool = False
    duration_seconds: float = 0.0
    width: int = 0
    height: int = 0
    fps: float = 0.0
    video_codec: Optional[str] = None
    pixel_format: Optional[str] = None
    audio_codec: Optional[str] = None
    has_audio: bool = False
    file_size_bytes: int = 0
    decode_errors: List[str] = Field(default_factory=list)
    browser_compatible: bool = False


class EducationalValidationResult(BaseModel):
    passed: bool
    scene_count_expected: int = 0
    scene_count_rendered: int = 0
    required_objects_present: bool = False
    missing_objects: List[str] = Field(default_factory=list)
    scientific_checks: List[str] = Field(default_factory=list)
    warnings: List[str] = Field(default_factory=list)
    errors: List[str] = Field(default_factory=list)


class ValidationReport(BaseModel):
    passed: bool
    technical: TechnicalValidationResult
    educational: EducationalValidationResult
    validated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class VideoMetadata(BaseModel):
    """Persisted metadata record for a generated educational video."""

    video_id: str
    job_id: str
    topic: str
    title: str
    class_level: int = Field(alias="class")
    subject: str
    board: str = "State Board"
    chapter: Optional[str] = None
    language: str = "English"
    status: str
    video_url: str
    thumbnail_url: Optional[str] = None
    subtitle_url: Optional[str] = None
    duration: float
    format: str = "mp4"
    resolution: str = "1920x1080"
    fps: float = 30.0
    size_bytes: int = 0
    generation_engine: str
    is_simulated: bool = False
    content_hash: str
    storage_provider: str = "local"
    local_video_path: Optional[str] = None
    local_thumbnail_path: Optional[str] = None
    local_subtitle_path: Optional[str] = None
    storyboard: Optional[Dict[str, Any]] = None
    validation: Optional[Dict[str, Any]] = None
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    model_config = {"populate_by_name": True}


